create table idempotency_records (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    idempotency_key varchar(255) not null,
    request_fingerprint varchar(64) not null,
    transfer_id bigint not null,
    created_at timestamptz not null default current_timestamp,

    constraint fk_idempotency_user_id foreign key (user_id) references users(id),
    constraint fk_idempotency_transfer_id foreign key (transfer_id) references transfers(id),

    constraint uq_user_id_idempotency_key unique (user_id, idempotency_key)
);
